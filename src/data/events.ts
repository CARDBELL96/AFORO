// DATOS DE DEMOSTRACIÓN. Todos los artistas, recintos, precios y fechas son ficticios.
// Modelo unificado de AFORO Fusion: combina la ficha emocional de Aforo (Claude: slug, acento,
// kicker, line-up con horarios) con la ficha técnica de tf (Gemini: código, coordenadas, sectores
// con disponibilidad, estado de venta y perfil acústico).
// Cuando exista backend, solo hay que sustituir `src/data/repository.ts`.

export type GenreId = 'rock-indie' | 'cumbia-chicha' | 'electronica' | 'urbana' | 'festivales' | 'cultura' | 'fiestas';

export type Accent = 'orange' | 'lime' | 'magenta' | 'blue' | 'amber' | 'teal' | 'cyan' | 'cream';

/** Estado comercial del evento (etiqueta superior de las tarjetas editoriales). */
export type SaleStatus = 'general' | 'preventa' | 'ultimos' | 'agotado';

export interface Genre {
  id: GenreId;
  label: string;
  blurb: string;
}

export interface TicketTier {
  id: string;
  name: string;
  note: string;
  price: number; // soles (PEN)
  /** `few` = últimas entradas (sigue a la venta). */
  status: 'available' | 'few' | 'sold_out';
  /** Porcentaje referencial de aforo libre en el sector (0–100). */
  remaining: number;
}

export interface LineupItem {
  name: string;
  time?: string;
  headliner?: boolean;
}

export interface EventImage {
  /** Fotografía real (remota). */
  photo: string;
  /** Póster ilustrado local: respaldo sin conexión. */
  poster: string;
  alt: string;
  position?: string;
}

export interface AforoEvent {
  id: string;
  slug: string;
  code: string;
  title: string;
  kicker: string;
  /** Línea de artistas (se muestra en coral, voz «dato»). */
  artist: string;
  genre: GenreId;
  tags: string[];
  city: string;
  district: string;
  venue: string;
  address: string;
  coordinates: string;
  startsAt: string; // ISO con offset de Lima (-05:00)
  endsAt?: string;
  doors: string;
  ageRule: string;
  description: string[];
  lineup: LineupItem[];
  tiers: TicketTier[];
  editorialTag: string;
  acoustic: string;
  sale: SaleStatus;
  saleLabel: string;
  image: EventImage;
  accent: Accent;
  featured?: boolean;
}

